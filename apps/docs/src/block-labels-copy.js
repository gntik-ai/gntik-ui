export function fixtureLabels(language, record = () => {}) {
  const es = language === 'es';
  const call = (key, args, result) => {
    record(key, args);
    return result;
  };
  return {
    ...copy[language],
    rangeSummary: (from, to, total) =>
      call('rangeSummary', [from, to, total], `${es ? 'Rango' : 'Range'} ${from}|${to}|${total}`),
    paginationNav: (noun) => call('paginationNav', [noun], `${es ? 'Páginas de' : 'Pages for'} ${noun}`),
    page: (number) => call('page', [number], `${es ? 'Ir a' : 'Go to'} ${number}`),
    removeFilter: (field, value) => call('removeFilter', [field, value], `${es ? 'Quitar' : 'Drop'} ${field}|${value}`),
    resultCount: (count) => call('resultCount', [count], `${es ? 'Encontrados' : 'Found'} ${count}`),
    selectionCount: (count) => call('selectionCount', [count], `${es ? 'Elegidos' : 'Chosen'} ${count}`),
    resizeColumn: (label) => call('resizeColumn', [label], `${es ? 'Ancho de' : 'Width for'} ${label}`),
    columnWidth: (width) => call('columnWidth', [width], `${width} ${es ? 'píxeles' : 'pixels wide'}`),
    selectRow: (label) => call('selectRow', [label], `${es ? 'Elegir' : 'Choose'} ${label}`),
    selectGroup: (group) => call('selectGroup', [group], `${es ? 'Elegir grupo' : 'Choose group'} ${group}`),
    groupRows: (count) => call('groupRows', [count], `${es ? 'filas' : 'records'}: ${count}`),
    rowActions: (label) => call('rowActions', [label], `${es ? 'Opciones de' : 'Options for'} ${label}`),
    loading: (caption) => call('loading', [caption], `${es ? 'Cargando' : 'Fetching'} ${caption}`),
    editLabel: (column, row) => call('editLabel', [column, row], `${column} ${es ? 'de' : 'on'} ${row}`),
    minimumValue: (min) => call('minimumValue', [min], `${es ? 'Mínimo' : 'Minimum'} ${min}`),
    maximumValue: (max) => call('maximumValue', [max], `${es ? 'Máximo' : 'Maximum'} ${max}`),
  };
}
