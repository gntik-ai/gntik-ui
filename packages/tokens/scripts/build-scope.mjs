// Generated scopes repeat aliases so var() resolves against the island's tokens.
import { readFileSync, writeFileSync } from 'node:fs';
import { readPalettes, TYPOGRAPHY_KEYS } from './palette-model.mjs';

function parse(css) {
  return Object.fromEntries(
    [
      ...css.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/(:where\(:root\)|:root|\.dark|\.high_contrast)\s*\{([^}]*)\}/g),
    ].map(([, selector, body]) => [
      selector,
      Object.fromEntries([...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, key, value]) => [key, value.trim()])),
    ]),
  );
}

export function renderScope(brandCss, pairingCss, palettes = {}, statusCss = '', typographyCss = '') {
  const brand = parse(brandCss);
  const defaults = { ...brand[':root'], ...parse(typographyCss)[':where(:root)'] };
  const typography = (values) =>
    Object.fromEntries(Object.entries(values).filter(([key]) => TYPOGRAPHY_KEYS.includes(key)));
  const colours = (values) =>
    Object.fromEntries(Object.entries(values).filter(([key]) => !TYPOGRAPHY_KEYS.includes(key)));
  // A palette may add chart series tokens. Every other palette, and high contrast, clears them,
  // so charts fall back to their default tokens instead of inheriting an outer palette's series.
  const seriesKeys = [
    ...new Set(Object.values(palettes).flatMap((blocks) => blocks.flatMap((values) => Object.keys(values)))),
  ]
    .filter((key) => /^--chart-series-\d+$/.test(key))
    .sort((a, b) => parseInt(a.slice(15), 10) - parseInt(b.slice(15), 10));
  const clearSeries = (values) =>
    Object.keys(values).some((key) => seriesKeys.includes(key))
      ? {}
      : Object.fromEntries(seriesKeys.map((key) => [key, 'initial']));
  const pairing = parse(pairingCss);
  const overridden = new Set([...Object.keys(brand['.dark']), ...Object.keys(brand['.high_contrast'])]);
  const light = {
    ...Object.fromEntries(Object.entries(brand[':root']).filter(([key]) => overridden.has(key))),
    ...pairing[':root'],
    'color-scheme': 'light',
  };
  const block = (selector, declarations) =>
    `${selector} {\n${Object.entries(declarations)
      .map(([key, value]) => `  ${key}: ${value};`)
      .join('\n')}\n}\n`;
  const guard = ':not(:where(.high_contrast, .high_contrast *))';
  const status = parse(statusCss);
  const greenLight = Object.fromEntries(Object.entries(brand[':root']).filter(([key]) => overridden.has(key)));
  const allPalettes = {
    green: [
      { ...greenLight, ...status[':root'] },
      { ...brand['.dark'], ...status['.dark'] },
    ],
    ...palettes,
  };
  let paletteScopes = '';
  for (const [id, [paletteLight, paletteDark]] of Object.entries(allPalettes)) {
    paletteScopes +=
      '\n' +
      block(`[data-palette="${id}"]`, {
        ...typography(defaults),
        ...typography(paletteLight),
        ...typography(paletteDark),
      });
    const target = `[data-palette="${id}"]${guard}`;
    // Repeat aliases on palette boundaries: inherited var() values have already resolved.
    const lightBlock = block(target, {
      ...colours(paletteLight),
      ...clearSeries(paletteLight),
      ...pairing[':root'],
    });
    // Green already has unscoped theme rules in brand.css. Keep palette resets
    // scoped so browsers without @scope retain the original green cascade.
    paletteScopes +=
      '\n' +
      (id === 'green'
        ? `@scope (:root, .light, .dark, .high_contrast) to (.light, .dark, .high_contrast) {\n${lightBlock}}\n`
        : lightBlock);
    paletteScopes +=
      `\n@scope (:root, .light, .dark, .high_contrast) to (.light, .dark, .high_contrast) {\n` +
      block(`:where(:scope.dark) ${target},\n:where(:scope.dark)${target}`, {
        ...colours(paletteDark),
        ...clearSeries(paletteDark),
        ...pairing['.dark'],
      }) +
      '}\n';
    // A theme boundary within the palette must reapply that palette, rather than green.
    paletteScopes +=
      `\n@scope ([data-palette="${id}"]) to ([data-palette]) {\n` +
      block(`.light${guard}`, { ...colours(paletteLight), ...pairing[':root'] }) +
      block(`.dark${guard}`, { ...colours(paletteDark), ...pairing['.dark'] }) +
      '}\n';
  }
  // Shared high contrast is never copied into an individual palette.
  paletteScopes +=
    '\n@scope (.high_contrast) to (.light, .dark) {\n' +
    block(':where(.high_contrast) :is([data-palette], .light, .dark)', {
      ...brand['.high_contrast'],
      ...pairing['.high_contrast'],
      '--success-strong': 'var(--success)',
    }) +
    '}\n';
  return (
    '/* Generated by scripts/build-scope.mjs. Do not edit. */\n' +
    block('.light', light) +
    '\n' +
    block('.dark', { 'color-scheme': 'dark' }) +
    '\n' +
    block('.high_contrast', {
      'color-scheme': 'dark',
      ...Object.fromEntries(seriesKeys.map((key) => [key, 'initial'])),
    }) +
    paletteScopes
  );
}

if (import.meta.main) {
  const source = new URL('../src/', import.meta.url);
  writeFileSync(
    new URL('scope.css', source),
    renderScope(
      readFileSync(new URL('brand.css', source), 'utf8'),
      readFileSync(new URL('pairing.css', source), 'utf8'),
      readPalettes((file) => readFileSync(new URL(file, source), 'utf8')),
      readFileSync(new URL('status.css', source), 'utf8'),
      readFileSync(new URL('typography.css', source), 'utf8'),
    ),
  );
}
